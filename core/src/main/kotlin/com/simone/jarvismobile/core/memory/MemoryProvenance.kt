package com.simone.jarvismobile.core.memory

import com.simone.jarvismobile.core.knowledge.KnowledgeText
import com.simone.jarvismobile.core.reliability.Quantities
import kotlinx.serialization.Serializable

/** Where a stored item came from. Decides whether it may ever become a durable personal fact. */
@Serializable
enum class MemorySource {
    /** The user said it ("il mio peso è 78 kg"). */
    USER_STATEMENT,
    USER_PREFERENCE,
    /** A tool reported it (a receipt). */
    TOOL_RESULT,
    DOCUMENT,
    ZIM,
    /** The model concluded it. Never a personal fact. */
    MODEL_INFERENCE,
    HYPOTHESIS,
    UNVERIFIED,
    /** A candidate answer the publication gate rejected. Never stored durably. */
    REJECTED_DRAFT,
}

@Serializable
enum class Verification { USER_ASSERTED, SOURCE_VERIFIED, UNVERIFIED, REJECTED }

/** ACTIVE = current; SUPERSEDED = replaced by a later correction (kept for audit/rectification); CONFLICT = two current-looking values nobody has resolved. */
@Serializable
enum class RecordStatus { ACTIVE, SUPERSEDED, CONFLICT }

/**
 * M1 — what may enter durable memory and as what. A sentence generated by the model never becomes a trusted personal fact; a user's
 * statement never becomes encyclopaedic truth; a rejected draft never enters at all. Explicit-save authorisation (confirmation,
 * credential rejection) stays where it already lives: this only classifies provenance.
 */
object MemoryAdmission {
    fun mayBeDurable(source: MemorySource): Boolean = when (source) {
        MemorySource.USER_STATEMENT, MemorySource.USER_PREFERENCE, MemorySource.TOOL_RESULT, MemorySource.DOCUMENT, MemorySource.ZIM -> true
        MemorySource.MODEL_INFERENCE, MemorySource.HYPOTHESIS, MemorySource.UNVERIFIED, MemorySource.REJECTED_DRAFT -> false
    }

    /** Only the user can make a PERSONAL fact; a document/ZIM/tool item is a referenced source, not something the user said. */
    fun mayBePersonalFact(source: MemorySource): Boolean = source == MemorySource.USER_STATEMENT || source == MemorySource.USER_PREFERENCE

    fun verificationFor(source: MemorySource): Verification = when (source) {
        MemorySource.USER_STATEMENT, MemorySource.USER_PREFERENCE -> Verification.USER_ASSERTED
        MemorySource.TOOL_RESULT, MemorySource.DOCUMENT, MemorySource.ZIM -> Verification.SOURCE_VERIFIED
        MemorySource.REJECTED_DRAFT -> Verification.REJECTED
        else -> Verification.UNVERIFIED
    }

    private val HYPOTHESIS = Regex("^(?:se |e se |immagina|ipotizza|supponi|poniamo|facciamo finta)|\\b(?:forse|magari|probabilmente|potrebbe essere|non sono sicur[oa]|credo che|penso che)\\b")

    /** A statement that is a supposition or a guess is not a fact about the user, whoever said it. */
    fun looksSpeculative(text: String): Boolean = HYPOTHESIS.containsMatchIn(KnowledgeText.fold(text).trim())

    /** The source a chat sentence should be filed under: speculation is a HYPOTHESIS and is not admitted. */
    fun sourceForUserText(text: String): MemorySource = if (looksSpeculative(text)) MemorySource.HYPOTHESIS else MemorySource.USER_STATEMENT
}

/** The subject and value of a simple self-statement, so a later correction can be linked to the earlier fact. */
object FactKey {
    data class Parsed(val key: String, val value: String, val correction: Boolean)

    private val CORRECTION = Regex("\\b(?:correggo|correzione|rettifico|anzi|in realta|ho sbagliato|scusa|ora|adesso|ormai|da oggi|ho cambiato|non e piu|non sono piu)\\b")
    private val NOUN_IS = Regex("\\b(?:il mio|la mia|i miei|le mie|mio|mia)\\s+([a-z]{3,})\\s+(?:e|sono|era|passa a)\\s+(.+)$")
    private val FIXED = listOf(
        Regex("\\bmi chiamo\\s+(.+)$") to "nome",
        Regex("\\b(?:abito|vivo|risiedo)\\s+(?:a|in)\\s+(.+)$") to "residenza",
        Regex("\\bsono nat[oa]\\s+(?:a|il|nel)\\s+(.+)$") to "nascita",
        Regex("\\blavoro\\s+(?:a|in|come|presso)\\s+(.+)$") to "lavoro",
    )
    private val SKIP = setOf("ora", "adesso", "ormai", "mio", "mia", "miei", "mie", "il", "la", "lo", "i", "le", "un", "una", "e", "è", "sono", "ho", "pesa", "correggo", "anzi", "scusa", "che", "di", "da", "oggi", "circa", "più", "piu")

    fun parse(text: String): Parsed? {
        val f = KnowledgeText.fold(text).replace(Regex("[’']"), " ").replace(Regex("\\s+"), " ").trim().trimEnd('.', '!', ' ')
        val correction = CORRECTION.containsMatchIn(f)
        NOUN_IS.find(f)?.let { return Parsed(it.groupValues[1], norm(it.groupValues[2]), correction) }
        for ((re, key) in FIXED) re.find(f)?.let { return Parsed(key, norm(it.groupValues[1]), correction) }
        // "ora peso 80 kg": the word right before the first number names what is measured
        val q = Quantities.extract(text).firstOrNull() ?: return null
        val before = f.substring(0, minOf(f.length, KnowledgeText.fold(text.substring(0, q.start)).length)).split(Regex("[^a-z]+")).filter { it.length >= 3 && it !in SKIP }
        val key = before.lastOrNull() ?: return null
        return Parsed(key.take(5), norm(q.value.stripTrailingZeros().toPlainString() + (q.unit?.let { " $it" } ?: "")), correction)
    }

    private fun norm(v: String) = v.trim().trimEnd('.', '!').replace(Regex("\\s+"), " ")
}

/**
 * M1 — rectification without losing history. A correction ("Correggo: ora peso 80 kg") marks the earlier active value SUPERSEDED and links the
 * two; the old record stays for audit. A new, different value for the same subject WITHOUT a correction cue leaves both marked CONFLICT
 * (nobody decided which is current). The same value twice is not stored twice.
 */
object MemoryLedger {
    data class Applied(val records: List<MemoryRecord>, val stored: MemoryRecord?, val outcome: Outcome)
    enum class Outcome { ADDED, SUPERSEDED_OLD, CONFLICT, DUPLICATE, REJECTED }

    fun apply(existing: List<MemoryRecord>, incoming: MemoryRecord): Applied {
        if (!MemoryAdmission.mayBeDurable(incoming.source)) return Applied(existing, null, Outcome.REJECTED)
        val parsed = if (MemoryAdmission.mayBePersonalFact(incoming.source)) FactKey.parse(incoming.text) else null
        if (parsed == null) return Applied(existing + incoming, incoming, Outcome.ADDED)
        val withKey = incoming.copy(subjectKey = parsed.key)
        val same = existing.filter { it.subjectKey == parsed.key && it.status != RecordStatus.SUPERSEDED && it.source.let(MemoryAdmission::mayBePersonalFact) }
        if (same.isEmpty()) return Applied(existing + withKey, withKey, Outcome.ADDED)
        val sameValue = same.any { FactKey.parse(it.text)?.value == parsed.value }
        if (sameValue) return Applied(existing, same.first(), Outcome.DUPLICATE)
        val ids = same.map { it.id }.toSet()
        return if (parsed.correction) {
            val stored = withKey.copy(supersedes = same.last().id)
            val next = existing.map { if (it.id in ids) it.copy(status = RecordStatus.SUPERSEDED, supersededBy = stored.id) else it } + stored
            Applied(next, stored, Outcome.SUPERSEDED_OLD)
        } else {
            val stored = withKey.copy(status = RecordStatus.CONFLICT)
            val next = existing.map { if (it.id in ids) it.copy(status = RecordStatus.CONFLICT) else it } + stored
            Applied(next, stored, Outcome.CONFLICT)
        }
    }

    /** The user decided which of the conflicting values is current: the others are kept as superseded. */
    fun resolve(records: List<MemoryRecord>, keepId: String): List<MemoryRecord> {
        val key = records.firstOrNull { it.id == keepId }?.subjectKey ?: return records
        return records.map {
            when {
                it.id == keepId -> it.copy(status = RecordStatus.ACTIVE)
                it.subjectKey == key && it.status == RecordStatus.CONFLICT -> it.copy(status = RecordStatus.SUPERSEDED, supersededBy = keepId)
                else -> it
            }
        }
    }

    /** What retrieval may offer: never a superseded value; a conflict is offered but marked so the answer can say it is unresolved. */
    fun retrievable(records: List<MemoryRecord>): List<MemoryRecord> = records.filter { it.status != RecordStatus.SUPERSEDED }

    fun promptText(record: MemoryRecord): String =
        if (record.status == RecordStatus.CONFLICT) record.text + " (informazioni in conflitto non ancora risolte)" else record.text
}
